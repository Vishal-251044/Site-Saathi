// SITE SAATHI - copy the sheet CSVs into design/data.js so the prototype
// always shows the same text as the app will (strings, lessons, quiz).
// Run after any CSV change:   node tools/build-design-data.js
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');
const SHEET = path.join(ROOT, 'content', 'sheet');

// Small CSV parser: quotes, "" escapes, commas and newlines inside quotes.
function parseCSV(text) {
  const rows = []; let row = [], f = '', q = false;
  text = text.replace(/^﻿/, '');
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) { if (c === '"') { if (text[i + 1] === '"') { f += '"'; i++; } else q = false; } else f += c; }
    else if (c === '"') q = true;
    else if (c === ',') { row.push(f); f = ''; }
    else if (c === '\n') { row.push(f); rows.push(row); row = []; f = ''; }
    else if (c !== '\r') f += c;
  }
  if (f || row.length) { row.push(f); rows.push(row); }
  const [head, ...body] = rows.filter((r) => r.some((x) => x !== ''));
  return body.map((r) => Object.fromEntries(head.map((h, i) => [h, r[i] ?? ''])));
}
const read = (name) => parseCSV(fs.readFileSync(path.join(SHEET, name), 'utf8'));

const strings = {};
for (const r of read('strings.csv')) strings[r.key] = { mr: r.mr, hi: r.hi, en: r.en };
const split = (s) => (s ? s.split('|').map((x) => x.trim()) : []);
const lessons = read('lessons.csv').map((r) => ({
  ...r, materials: split(r.materials), steps: split(r.steps), safety: split(r.safety),
  mistakes: split(r.mistakes), img: split(r.img), duration_min: Number(r.duration_min) || 0,
}));
const quiz = read('quiz.csv').map((r) => ({ ...r, q_no: Number(r.q_no) }));

const out = `// GENERATED by tools/build-design-data.js from content/sheet/*.csv - do not edit by hand.\n` +
  `window.SS_DATA = ${JSON.stringify({ built: new Date().toISOString().slice(0, 10), strings, lessons, quiz }, null, 1)};\n`;
fs.writeFileSync(path.join(ROOT, 'design', 'data.js'), out);
console.log(`design/data.js: ${Object.keys(strings).length} strings, ${lessons.length} lesson rows, ${quiz.length} quiz rows`);
